import { assertSimulated } from "@/lib/guards";
import { formatUsd } from "@/lib/money";
import type { Action, Approval, ResponseLetter } from "@/lib/types";
import { NotApproved, type HospitalConnector, type ResponseFacts } from "./types";

export const RESPONSE_DELAY_DAYS = 12;
export const DEMO_PARTNER_NAME = "Riverbend Community Hospital";
export const SYNTHETIC_FOOTER = "SYNTHETIC — demo partner response, generated by Kindred Snap for a demonstration";

const DAY_MS = 86_400_000;

/** cents × percent / 100, rounded half up to the cent, without floating point */
function percentOf(cents: number, percent: number): number {
  return Math.floor((cents * percent + 50) / 100);
}

/** The demo partner. Nothing leaves the process: `send` only records that a send was simulated, `response` writes the letter from case facts. */
export class DemoPartnerHospital implements HospitalConnector {
  readonly kind = "demo_partner_synthetic" as const;

  async send(action: Action, approval: Approval | undefined, now: string): Promise<{ simulated: true; sentAt: string }> {
    assertSimulated();
    if (!approval?.approvedAt) throw new NotApproved(`Action ${action.id} (${action.kind}) has no approval on record`);
    return { simulated: true, sentAt: now };
  }

  async response(input: { caseId: string; sentAt: string; now: string; facts: ResponseFacts }): Promise<ResponseLetter | null> {
    const { caseId, sentAt, now, facts } = input;
    const receivedMs = Date.parse(sentAt) + RESPONSE_DELAY_DAYS * DAY_MS;
    if (Date.parse(now) < receivedMs) return null;
    const receivedAt = new Date(receivedMs).toISOString();
    const tier = facts.tierPercent;
    // the discount is what rounds half up (as estimateReduction does), so the letter and the app's estimate agree to the cent
    const newBalanceCents = facts.correctedCents - (tier === null ? 0 : percentOf(facts.correctedCents, tier));
    const quotedLine = facts.removedLineCents > 0 ? `${facts.removedLineLabel} ${formatUsd(facts.removedLineCents)}` : "";

    const paragraphs = [
      `Patient Financial Services, ${DEMO_PARTNER_NAME} (demo partner)`,
      `Date: ${receivedAt.slice(0, 10)}`,
      `Re: ${facts.patientName}. We reviewed the request sent on ${sentAt.slice(0, 10)} about the statement asking for ${formatUsd(facts.askedCents)}.`,
      quotedLine
        ? `Medicare's notice shows no patient responsibility for the line "${quotedLine}", and we have removed it from the patient's balance. The corrected balance is ${formatUsd(facts.correctedCents)}.`
        : `The charges on the statement match Medicare's notice, so the balance stays at ${formatUsd(facts.correctedCents)}.`,
      tier === null
        ? "No financial assistance tier was applied."
        : `The financial assistance application was approved at the ${tier}% tier. A discount of ${formatUsd(facts.correctedCents - newBalanceCents)} has been applied to the corrected balance.`,
      `The new balance is ${formatUsd(newBalanceCents)}. No collection activity occurred during review.`,
      SYNTHETIC_FOOTER,
    ];

    return {
      id: `letter-${caseId}`,
      caseId,
      text: paragraphs.join("\n\n"),
      quotedLine,
      tierApplied: tier,
      newBalanceCents,
      receivedAt,
      simulated: true,
    };
  }
}
